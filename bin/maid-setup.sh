#!/usr/bin/env bash
# Maid BT first-run wizard: discovers hardware, writes configs, offers
# opt-ins. Rerunnable anytime; safe to run twice (asks before overwrite).
# Plain terminal prompts only — no new dependencies.
set -u

CONF="$HOME/.config/bluetooth-buds.conf"
WCONF="$HOME/.config/maid-watcher/config.json"

say()  { echo "==> $*"; }
ask()  { printf '%s ' "$1" >&2; read -r REPLY; }

pick_bt_device() {
  say "looking for bluetooth audio devices (make earbuds discoverable)..." >&2
  mapfile -t DEVS < <(bluetoothctl devices 2>/dev/null | grep "^Device" || true)
  if [ "${#DEVS[@]}" -eq 0 ]; then
    say "none found — pair first: bluetoothctl pair <MAC>, then rerun me"
    return 1
  fi
  local i=1
  for d in "${DEVS[@]}"; do echo "  $i) $d" >&2; i=$((i+1)); done
  ask "pick your earbuds [1-${#DEVS[@]}]:"
  local n="$REPLY"
  [[ "$n" =~ ^[0-9]+$ ]] && [ "$n" -ge 1 ] && [ "$n" -le "${#DEVS[@]}" ] || return 1
  echo "${DEVS[$((n-1))]}" | awk '{print $2}'
}

pick_sink() {
  say "audio outputs:" >&2
  pactl list short sinks 2>/dev/null >&2 || true
  local def
  def=$(pactl info 2>/dev/null | sed -n 's/^Default Sink: //p')
  ask "fallback speakers/DAC (Enter = $def):"
  echo "${REPLY:-$def}"
}

valid_mac() { [[ "$1" =~ ^([0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2}$ ]]; }
valid_sink() { [[ "$1" =~ ^[A-Za-z0-9_.,:/+=@-]+$ ]]; }

# ---- 1. earbuds + fallback ----
if [ -f "$CONF" ]; then
  say "$CONF exists — kept (delete it to redo this step)"
else
  MAC=$(pick_bt_device) || exit 1
  valid_mac "$MAC" || { echo "bad MAC, quitting"; exit 1; }
  SINK=$(pick_sink)
  valid_sink "$SINK" || { echo "odd sink name, quitting"; exit 1; }
  mkdir -p "$(dirname "$CONF")"
  { echo "# generated by maid-setup on $(date +%F)";
    echo "BUDS_MAC=\"$MAC\""; echo "FALLBACK_SINK=\"$SINK\""; } > "$CONF"
  say "wrote $CONF"
fi

# ---- 2. watcher config seed ----
if [ -f "$WCONF" ]; then
  say "$WCONF exists — kept"
else
  MAC2=$(grep -oE 'BUDS_MAC="[^"]+"' "$CONF" 2>/dev/null | cut -d'"' -f2 || true)
  if [ -n "$MAC2" ]; then
    mkdir -p "$(dirname "$WCONF")"
    python3 - "$MAC2" <<'EOF' > "$WCONF" || true
import json, sys
mac = sys.argv[1]
print(json.dumps({
  "devices": [{"mac": mac, "name": "My Earbuds", "priority": 1,
               "auto_reconnect": True, "prefer_profile": "a2dp"}],
  "reconnect": {"initial_delay_s": 5, "max_delay_s": 120, "give_up_after": 10},
  "calls": {"enabled": True, "pause_media": True, "mute_discord": True,
            "max_call_mode_s": 300},
  "battery": {"warn_percent": 25, "critical_percent": 12, "poll_s": 120},
  "saver": {"enabled": False, "idle_minutes": 30},
  "laptop": {"mode": "auto"}
}, indent=2))
EOF
    say "seeded $WCONF from your earbuds"
  else
    say "skipped watcher seed (no earbuds configured)"
  fi
fi

# ---- 3. opt-ins ----
ask "enable Maid Watcher autostart (calls, battery, reconnects)? [y/N]:"
case "$REPLY" in [Yy]*)
  if [ "$(ps -p 1 -o comm= 2>/dev/null || echo unknown)" = "systemd" ]; then
    systemctl --user enable --now maid-watcher.service 2>/dev/null \
      && say "watcher on (supervised)" || say "could not enable service"
  else
    mkdir -p "$HOME/.config/autostart"
    sed -e "s|/home/EXAMPLEUSER/|${HOME//&/\\&}|g" \
      "$(cd "$(dirname "$0")/../watcher" && pwd)/maid-watcher.desktop" \
      > "$HOME/.config/autostart/maid-watcher.desktop" 2>/dev/null \
      && say "watcher on (autostart)" || say "could not write autostart entry"
  fi ;;
esac

ask "keep BT audio warm (no 1s late start, more earbud drain)? [y/N]:"
case "$REPLY" in [Yy]*)
  mkdir -p "$HOME/.config/wireplumber/wireplumber.conf.d"
  cp -a "$(cd "$(dirname "$0")/../wireplumber" && pwd)/51-bt-no-suspend.conf" \
    "$HOME/.config/wireplumber/wireplumber.conf.d/" 2>/dev/null \
    && say "warm audio on — restart wireplumber to apply" || say "copy failed" ;;
esac

say "done. add the BT Earbuds widget, log out/in. test: bluetooth-toggle.sh status"
